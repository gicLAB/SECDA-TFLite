#!/bin/bash

# Documentation
# What is this script for?
# This script is used to run the benchmark suite on the board and process the results
# It runs the benchmarks in the configs.sh arrays
# It also runs the inference diff binary to verify the correctness of the accelerator
# It also runs the benchmark binary to collect the performance numbers

# How to use this script?
# ./run_collect.sh [process_on_fpga] [skip_inf_diff]
# process_on_fpga - 0 or 1 - 0 to not process the results on the fpga and 1 to process the results on the fpga
# skip_inf_diff - 0 or 1 - 0 to run the inference diff binary and 1 to skip running the inference diff binary

# During each benchmark run, the script will load the bitstream if the hardware is different from the previous run
# It will also clear the cache if the model is different from the previous run

# It generates a file called commands.txt which contains all the commands that were run on the board
# It also generates a file called tmp/${runname}_id.txt which contains the output of the inference diff binary
# It also generates a file called tmp/${runname}_bm.txt which contains the output of the benchmark binary
# It also generates a file called tmp/${runname}_prf.csv which contains the acc_profile generated by the delegate
# It also generates a file called tmp/${runname}_layer.csv which contains the layer profile generated by the benchmark binary

# Do not run this script directly, run secda_apps_evaluation_suite.sh instead

source configs.sh
prev_failed=0
collect_power=0
prev_hw=${hw_array[0]}
prev_hw=""
prev_model=""

if [ $# -eq 1 ]; then
  collect_power=$1
fi

# create a file to store commands
rm -f ./commands.txt
touch ./commands.txt
rm -f ./runs.csv
touch ./runs.csv

# delete the tmp directory
rm -rf ./tmp
mkdir ./tmp

function ctrl_c() {
  echo "Exiting"
  exit 1
}

trap ctrl_c INT

bitstream_dir="${board_dir}/bitstreams"
scripts_dir="${board_dir}/scripts"
board_user="${board_user}"
ld_bst=${ld_bst}

# echo "bitstream_dir=${bitstream_dir}"
# echo "scripts_dir=${scripts_dir}"
# echo "board_user=${board_user}"
# echo "ld_bst=${ld_bst}"
# exit 1

hw_length=${#hw_array[@]}
for ((i = 0; i < hw_length; i++)); do
  index=$((i + 1))
  HW=${hw_array[$i]}
  TAG=${tag_array[$i]}
  APP=${app_array[$i]}
  MODEL=${model_array[$i]}
  CMD=${cmd_array[$i]}
  DEL=${del_array[$i]}
  DEL_VERSION=${del_version_array[$i]}
  VERSION=${version_array[$i]}

  runname=${TAG}
  echo "========================================================================"
  echo "${runname} ${index}/${hw_length}"
  echo "========================================================================"

  #if prev_hw was different then load base bitstream and sleep 1 second
  if [ ${ld_bst} -eq 1 ]; then
    if [ ${prev_failed} -eq 1 ] || [ "${prev_hw_version}" != "${HW}_${VERSION}" ]; then
      echo "Loading bitstream ${HW}_${VERSION}.bit"
      echo "sudo -S bash -c 'source /etc/profile.d/xrt_setup.sh; source /etc/profile.d/pynq_venv.sh; python3 ${scripts_dir}/load_bitstream.py ${bitstream_dir}/${HW}_${VERSION}.bit -q'" >> commands.txt

      # this template is customized for rpp pynq board
      sudo -S bash -c 'source /etc/profile.d/xrt_setup.sh; source /etc/profile.d/pynq_venv.sh; python3 '${scripts_dir}'/load_bitstream.py '${bitstream_dir}'/'${HW}'_'${VERSION}'.bit -q'

      if [ $? -ne 0 ]; then prev_failed=1 && echo "Load bitstream failed ${bitstream_dir}/${HW}_${VERSION}.bit" && continue; fi

      echo "Clearing cache"
      sudo sh -c "/bin/echo 3 > /proc/sys/vm/drop_caches" # Clear cache
    fi
  fi
  
  if [ "${prev_model}" != "${MODEL}" ]; then
    echo "Clearing cache"
    sudo sh -c "/bin/echo 3 > /proc/sys/vm/drop_caches" # Clear cache
  fi
  prev_failed=0
  prev_hw=${HW}
  prev_hw_version=${HW}_${VERSION}
  prev_model=${MODEL}


  if [ "${APP}" == "eval_model" ]; then
    echo "Running evaluation model"
    rm -f ./tmp/${runname}_*.txt
    echo "echo '${pass}' | sudo -S timeout --foreground 60 ${CMD}" >>commands.txt
    echo "${pass}" | sudo -S timeout --foreground 60 ${CMD} >tmp/${runname}.txt 2>&1
    if [ $? -ne 0 ]; then
      echo "run failed"
      echo "sudo timeout --foreground 60 ${CMD}"
      prev_failed=1
      continue
    fi
  elif [ "${APP}" == "eval_model_accuracy" ]; then
    echo "Running evaluation model accuracy"
    rm -f ./tmp/${runname}_*.txt
    echo "echo '${pass}' | sudo -S timeout --foreground 5h ${CMD}" >>commands.txt
    echo "${pass}" | sudo -S timeout --foreground 5h ${CMD} >tmp/${runname}.txt 2>&1
    if [ $? -ne 0 ]; then
      echo "run failed"
      echo "sudo timeout --foreground 5h ${CMD}"
      prev_failed=1
      continue
    fi
  elif [ "${APP}" == "imagenet_image_classification" ]; then
    echo "Running Imagenet Image Classification-Accuracy Test!!"
    rm -f ./tmp/${runname}_*.txt
    echo "echo '${pass}' | sudo -S timeout --foreground 10h ${CMD}" >>commands.txt
    echo "${pass}" | sudo -S timeout --foreground 10h ${CMD} >tmp/${runname}.txt 2>&1
    if [ $? -ne 0 ]; then
      echo "run failed"
      echo "sudo timeout --foreground 10h ${CMD}"
      prev_failed=1
      continue
    fi
    echo "✅ Completed Imagenet Image Classification-Accuracy Test!!"

  elif [ "${APP}" == "benchmark_model" ]; then
    echo "Running benchmark model"
    rm -f "./tmp/${runname}_*.txt" ./prf.csv ./layer.csv

    if [ ${collect_power} -eq 1 ]; then
      # Where the power logger script lives on the Kria
      # POWER_DIR=${POWER_DIR:-/home/ubuntu/power_measurement}
      POWER_SCRIPT=${POWER_SCRIPT:-log_power_KRIA.sh}   # executable file in $POWER_DIR
      SCRIPT_NAME="${POWER_SCRIPT}"

      # mkdir -p result tmp
    
      # start logger (non-interactive) and replace subshell with the logger
      (
        set -e
        cd "${scripts_dir}"
        chmod +x "${SCRIPT_NAME}"
        # replace this shell with the logger => $! becomes logger’s PID
        exec "./${SCRIPT_NAME}" --auto --interval 0.05 "${TAG}_power.txt"
      ) >"tmp/${runname}_power_stdout.txt" 2>"tmp/${runname}_power_stderr.txt" &
      POWER_PID=$!

      # Ensure we stop logger if interrupted
      cleanup_power() {
        if kill -0 "${POWER_PID}" 2>/dev/null; then
          kill "${POWER_PID}" 2>/dev/null || true
          wait "${POWER_PID}" 2>/dev/null || true
        fi
      }
      trap cleanup_power INT TERM
    fi
    # Run the app
    echo "echo '${pass}' | sudo -S timeout --foreground 40m ${CMD}" >> commands.txt
    echo "${pass}" | sudo -S timeout --foreground 40m ${CMD} > "tmp/${runname}.txt" 2>&1
    # echo "${pass}" | sudo -S bash -c "timeout --foreground 40m ${CMD}" > "tmp/${runname}.txt" 2>&1
    app_rc=$?

    if [ ${collect_power} -eq 1 ]; then
      # Stop the logger immediately when app finishes
      if kill -0 "${POWER_PID}" 2>/dev/null; then
        kill "${POWER_PID}" 2>/dev/null || true
        wait "${POWER_PID}" 2>/dev/null || true
      fi
      # Copy power log to result/ (on Kria) for host to fetch later
      if [ -f "${scripts_dir}/${TAG}_power.txt" ]; then
        mv -f "${scripts_dir}/${TAG}_power.txt" "tmp/${TAG}_power.txt"
        echo "✅ Saved power log: result/${TAG}_power.txt"
      else
        echo "⚠️  Power log not found at ${scripts_dir}/${TAG}_power.txt"
      fi
    fi

    # Record runtime
    rtime=$(cat runtime.txt 2>/dev/null || echo NA)
    echo "${MODEL},${HW},${VERSION},${DEL},${DEL_VERSION},${THREAD},${NUM_RUN},${rtime}" >> runs.csv



    if [ ${app_rc} -ne 0 ]; then
      echo "run failed"
      echo "sudo timeout --foreground 40m ${CMD}"
      prev_failed=1
      continue
    fi
    # move profiling CSVs if present
    [ -e prf.csv ]   && mv -f prf.csv   "tmp/${runname}_prf.csv"
    [ -e layer.csv ] && mv -f layer.csv "tmp/${runname}_layer.csv"


  elif [ "${APP}" == "inference_diff" ]; then
    echo "Running inference diff"
    rm -f ./tmp/${runname}_*.txt
    echo "echo '${pass}' | sudo -S timeout --foreground 60 ${CMD}" >>commands.txt
    echo "${pass}" | sudo -S timeout --foreground 60 ${CMD} >tmp/${runname}.txt 2>&1
    if [ $? -ne 0 ]; then
      echo "run failed"
      echo "sudo timeout --foreground 60 ${CMD}"
      prev_failed=1
      continue
    fi
    
  else
    echo "!!!APPs NOT Supported!!!"
    echo "Exiting Apps Evaluation..."
    exit 1
  fi

  # usedel="--use_${DEL}=true"
  # if [ ${HW} == "CPU" ]; then usedel=""; fi


done # HW

# Collect CPU idle power for ~1 min
if [ "${collect_power}" -eq 1 ]; then
  echo "📉 Collecting idle power for ~60s..."
  (
    set -e
    cd "${scripts_dir}"
    chmod +x "${SCRIPT_NAME}"
    # Replace the subshell with the logger so $! is the logger's PID.
    # Write directly to a stable filename for idle measurement.
    exec "./${SCRIPT_NAME}" --auto --interval 0.05 "cpu_idle_power.txt"
  ) >"tmp/${runname}_idle_power_stdout.txt" 2>"tmp/${runname}_idle_power_stderr.txt" &

  POWER_PID=$!

  # Let it sample for ~60 seconds (adjust if you want longer/shorter)
  sleep 60

  # Stop the logger cleanly and reap it
  if kill -0 "${POWER_PID}" 2>/dev/null; then
    kill "${POWER_PID}" 2>/dev/null || true
    wait "${POWER_PID}" 2>/dev/null || true
  fi

  # Copy idle power log into tmp/ for host retrieval
  if [ -f "${scripts_dir}/cpu_idle_power.txt" ]; then
    mv -f "${scripts_dir}/cpu_idle_power.txt" "tmp/cpu_idle_power.txt"
    echo "✅ Saved idle power log: tmp/cpu_idle_power.txt"
  else
    echo "⚠️  Idle power log not found at ${scripts_dir}/cpu_idle_power.txt"
  fi
fi

if [ -e runs.csv ]; then
  mv -f runs.csv tmp/runs.csv
fi

rm -f sds_trace_data.dat
rm -f layer.csv
rm -f prf.csv
rm -f runtime.txt
